"""Extra site languages (all remaining EU languages) as overlays.

i18n/_en.json   — list of the English template strings (inner HTML of every <span data-l="en">), regenerated by
                  `python3 tools/extra.py extract` whenever src/site.html gains new text.
i18n/<lang>.json — {"name": "PT · Português", "og": "pt_PT", "meta": [title, desc],
                    "t": {english string: translation, ...},   # missing strings fall back to English
                    "news": {news, head, intro, sources, read, all, home, latest, cta_h, cta_p, cta},
                    "pages": {services, cases, more, faq, crumbs, ours, work},
                    "videos": [title, intro, all], "ok": "Copied! ..."}
build.py injects the translations into the template at build time, so src/site.html keeps only the core 11 languages.
News articles are written in the core languages; extra languages link to the English news.
"""
import json, glob, os, re, html, sys

SPAN_EN = re.compile(r'<span data-l="en">((?:[^<]|<span[^>]*>[^<]*</span>|<(?!/?span\b)[^>]*>)*?)</span>')


def load():
    out = {}
    for f in sorted(glob.glob("i18n/*.json")):
        code = os.path.basename(f)[:-5]
        if code.startswith("_"):
            continue
        out[code] = json.load(open(f, encoding="utf-8"))
    return out


def extract():
    s = open("src/site.html", encoding="utf-8").read()
    strings = list(dict.fromkeys(SPAN_EN.findall(s)))
    json.dump(strings, open("i18n/_en.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    return strings


def inject(tpl, code, data):
    """Add <span data-l=code> after every English span, using data['t'] (fallback: English)."""
    t = data.get("t", {})
    def rep(m):
        en = m.group(1)
        tr = t.get(en)
        if tr is None:
            inner = en
        elif "<" in en:          # keep markup given in the translation as is
            inner = tr
        else:
            inner = html.escape(tr, quote=False).replace("'", "&#x27;")
        return m.group(0) + f'<span data-l="{code}">{inner}</span>'
    return SPAN_EN.sub(rep, tpl)


if __name__ == "__main__" and sys.argv[1:] == ["extract"]:
    print(len(extract()), "strings")
